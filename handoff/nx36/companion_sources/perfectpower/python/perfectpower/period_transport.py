"""Exact finite spectral objects and checked paths of period transformations.

A PhaseObject is a Q-linear combination of characters of C_N. Nonnegative
integer coefficients give an actual complex representation; arbitrary rational
coefficients give a formal element of its Q-linearized representation ring.
The direct sum/tensor/dual operations are representation operations. Transport
arrows below are checked *rewrite paths*, not unspecified equivariant maps or
claims about higher categories. Computations here are exact Python, not Lean.
"""
from dataclasses import dataclass
from fractions import Fraction as Q
from functools import lru_cache
from math import comb, factorial, gcd, lcm


def _integer(value, name, minimum=None):
    if type(value) is not int or (minimum is not None and value < minimum):
        raise ValueError(name + ' must be an integer' + (' >= ' + str(minimum) if minimum is not None else ''))
    return value


def _rational(value):
    if type(value) not in (int, Q, str):
        raise ValueError('exact integer, Fraction or rational string required')
    return Q(value)


@dataclass(frozen=True)
class PhaseObject:
    conductor: int
    terms: tuple

    def __post_init__(self):
        n = _integer(self.conductor, 'ambient conductor', 1)
        data = {}
        entries = self.terms.items() if isinstance(self.terms, dict) else self.terms
        for k, coefficient in entries:
            k = _integer(k, 'phase exponent') % n
            data[k] = data.get(k, Q(0)) + _rational(coefficient)
        object.__setattr__(self, 'terms', tuple(sorted((k, v) for k, v in data.items() if v)))

    @property
    def dimension(self):
        return sum((v for _, v in self.terms), Q(0))

    @property
    def is_representation(self):
        return all(v.denominator == 1 and v >= 0 for _, v in self.terms)

    @property
    def has_real_form(self):
        return self.is_representation and self == self.dual()

    @property
    def minimal_conductor(self):
        result = 1
        for k, _ in self.terms:
            result = lcm(result, self.conductor // gcd(k, self.conductor))
        return result

    def packet(self):
        return dict(conductor=self.conductor, terms=[[k, str(v)] for k, v in self.terms])

    @classmethod
    def from_packet(cls, packet):
        if not isinstance(packet, dict) or set(packet) != {'conductor', 'terms'}:
            raise ValueError('phase packet requires conductor and terms')
        return cls(packet['conductor'], tuple(tuple(t) for t in packet['terms']))

    def lift(self, conductor):
        """Inflate through C_M -> C_N; preserve every complex eigenphase."""
        m = _integer(conductor, 'lift conductor', 1)
        if m % self.conductor:
            raise ValueError('lift conductor must be a multiple of source conductor')
        return PhaseObject(m, tuple((k * (m // self.conductor), v) for k, v in self.terms))

    def restrict(self, conductor):
        """Restrict to C_n inside C_N, generated by g_N**(N/n)."""
        n = _integer(conductor, 'subgroup conductor', 1)
        if self.conductor % n:
            raise ValueError('subgroup conductor must divide source conductor')
        return PhaseObject(n, self.terms)

    def power(self, exponent):
        a = _integer(exponent, 'power')
        return PhaseObject(self.conductor, tuple((k * a, v) for k, v in self.terms))

    def dual(self):
        return self.power(-1)

    def scale(self, coefficient):
        a = _rational(coefficient)
        return PhaseObject(self.conductor, tuple((k, a * v) for k, v in self.terms))

    def direct_sum(self, other):
        n = lcm(self.conductor, other.conductor)
        return PhaseObject(n, self.lift(n).terms + other.lift(n).terms)

    def tensor(self, other):
        n = lcm(self.conductor, other.conductor)
        return PhaseObject(n, tuple((k + j, a * b)
            for k, a in self.lift(n).terms for j, b in other.lift(n).terms))

    def phases(self):
        """Exact formal trace, keyed by angles modulo one; no numeric rounding."""
        return tuple((Q(k, self.conductor), v) for k, v in self.terms)

    def cyclotomic_trace(self, exponent=1, *, max_conductor=4096):
        """Canonical Q[z]/Phi_N trace by exact monic polynomial division.

        Conductor guard avoids allocating a dense polynomial at huge levels.
        The formal trace from phases() requires no dense polynomial allocation.
        """
        _integer(max_conductor, 'trace conductor budget', 1)
        if self.conductor > max_conductor:
            raise ValueError('dense cyclotomic trace exceeds conductor budget')
        obj = self.power(exponent)
        polynomial = [Q(0)] * (max((k for k, _ in obj.terms), default=0) + 1)
        for k, v in obj.terms:
            polynomial[k] = v
        return _divide_monic(polynomial, _cyclotomic(self.conductor))[1]


def _divide_monic(numerator, denominator):
    values = list(numerator)
    while len(values) > 1 and not values[-1]:
        values.pop()
    quotient = [Q(0)] * max(1, len(values) - len(denominator) + 1)
    nonzero = tuple((j, v) for j, v in enumerate(denominator) if v)
    while len(values) >= len(denominator) and any(values):
        shift, factor = len(values) - len(denominator), values[-1]
        quotient[shift] = factor
        for j, value in nonzero:
            values[j + shift] -= factor * value
        while len(values) > 1 and not values[-1]:
            values.pop()
    while len(quotient) > 1 and not quotient[-1]:
        quotient.pop()
    return tuple(quotient), tuple(values)


@lru_cache(maxsize=256)
def _cyclotomic(n):
    # Phi_n = (x^n-1) / product_(d|n,d<n) Phi_d, all exact monic divisions.
    polynomial = tuple([-1] + [0] * (n - 1) + [1])
    for divisor in range(1, n):
        if n % divisor == 0:
            polynomial, remainder = _divide_monic(polynomial, _cyclotomic(divisor))
            if any(remainder):
                raise ArithmeticError('cyclotomic monic division was not exact')
    return polynomial



@lru_cache(None)
def _bernoulli(n):
    if n == 0:
        return Q(1)
    return -sum((comb(n + 1, k) * _bernoulli(k) for k in range(n)), Q(0)) / (n + 1)


def even_period_coefficient(obj, weight=2):
    """Coefficient of pi**weight in sum m_k Re Li_weight(zeta_N**k).

    For positive even weight, the Fourier/Bernoulli evaluation is absolutely
    convergent even at phase one. This map is additive, not a tensor functor
    into multiplication of integral values.
    """
    if type(weight) is not int or not 2 <= weight <= 64 or weight % 2:
        raise ValueError('an even weight from 2 through 64 is required')
    factor = Q((-1) ** (weight // 2 + 1) * 2 ** (weight - 1), factorial(weight))
    return factor * sum((v * sum((comb(weight, j) * _bernoulli(j) * x ** (weight - j)
        for j in range(weight + 1)), Q(0)) for x, v in obj.phases()), Q(0))


def primitive_phases(conductor):
    n = _integer(conductor, 'conductor', 1)
    return PhaseObject(n, tuple((k, 1) for k in range(n) if gcd(k, n) == 1))


def root_fiber(base_conductor, degree, base_exponent=1, *, primitive=False):
    """The degree roots of z**degree=zeta_base**base_exponent.

    Primitive=True retains only primitive roots at the enlarged conductor.
    This is the Galois-conjugate fiber when gcd(base_exponent,base)=1.
    """
    n = _integer(base_conductor, 'base conductor', 1)
    d = _integer(degree, 'fiber degree', 1)
    a = _integer(base_exponent, 'base exponent') % n
    if type(primitive) is not bool:
        raise ValueError('primitive flag must be Boolean')
    m = n * d
    return PhaseObject(m, tuple((a + n * j, 1) for j in range(d)
        if not primitive or gcd(a + n * j, m) == 1))


def _mobius(n):
    result, p = 1, 2
    while p * p <= n:
        if n % p == 0:
            n //= p
            if n % p == 0:
                return 0
            result = -result
        p += 1
    return -result if n > 1 else result


def ramanujan_trace(conductor, exponent=1):
    """Integer character trace on the full primitive phase representation."""
    n = _integer(conductor, 'conductor', 1)
    a = _integer(exponent, 'exponent')
    d = gcd(n, a)
    return sum(k * _mobius(n // k) for k in range(1, d + 1) if d % k == 0)


def _apply(obj, operation, parameters):
    if operation == 'identity' and not parameters:
        return obj
    if operation == 'dual' and not parameters:
        return obj.dual()
    if operation in ('lift', 'restrict') and set(parameters) == {'conductor'}:
        return getattr(obj, operation)(parameters['conductor'])
    if operation == 'power' and set(parameters) == {'exponent'}:
        return obj.power(parameters['exponent'])
    raise ValueError('unsupported transport rule or invalid parameters')


@dataclass(frozen=True)
class TransportArrow:
    """A path in the category generated by explicitly replayable rewrite rules."""
    source: PhaseObject
    target: PhaseObject
    steps: tuple

    def __post_init__(self):
        current = self.source
        normalized = []
        for operation, params in self.steps:
            params = tuple(sorted(dict(params).items()))
            current = _apply(current, operation, dict(params))
            normalized.append((operation, params))
        if current != self.target:
            raise ValueError('transport target does not match replay')
        object.__setattr__(self, 'steps', tuple(normalized))

    @classmethod
    def rule(cls, source, operation, **parameters):
        target = _apply(source, operation, parameters)
        return cls(source, target, ((operation, tuple(sorted(parameters.items()))),))

    def then(self, other):
        if self.target != other.source:
            raise ValueError('transport composition requires equal intermediate objects')
        return TransportArrow(self.source, other.target, self.steps + other.steps)

    def receipt(self):
        return dict(schema='pp-period-transport/1', source=self.source.packet(), target=self.target.packet(),
            steps=[dict(operation=op, parameters=dict(params)) for op, params in self.steps],
            phase_preserving=self.source.phases() == self.target.phases(), exact_replay=True)


def verify_transport(receipt):
    try:
        if receipt['schema'] != 'pp-period-transport/1' or receipt['exact_replay'] is not True:
            return False
        source, target = PhaseObject.from_packet(receipt['source']), PhaseObject.from_packet(receipt['target'])
        path = TransportArrow(source, target, tuple((step['operation'], tuple(step['parameters'].items())) for step in receipt['steps']))
        return path.receipt() == receipt
    except (KeyError, TypeError, ValueError, IndexError, ZeroDivisionError):
        return False


def transport_closure(seeds, rules, *, max_objects=10000):
    """Saturate a finite requested rule system; fail if a domain/budget fails.

    Rules are (operation, parameter-dict). An inapplicable rule is an error,
    never silently interpreted as an identity. No universal finiteness claim.
    """
    _integer(max_objects, 'closure object budget', 1)
    rules = tuple(rules)
    objects = list(dict.fromkeys(seeds))
    if len(objects) > max_objects:
        raise ValueError('transport closure exceeds object budget')
    known = set(objects)
    cursor = 0
    while cursor < len(objects):
        source = objects[cursor]
        cursor += 1
        for operation, params in rules:
            target = _apply(source, operation, params)
            if target not in known:
                if len(objects) >= max_objects:
                    raise ValueError('transport closure exceeds object budget')
                known.add(target)
                objects.append(target)
    return tuple(objects)
