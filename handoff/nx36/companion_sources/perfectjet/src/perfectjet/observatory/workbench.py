"""Local, dependency-free interface to the exact Observatory compiler.

HTTP is only a presentation adapter. All answers come from the same public
Python classes used by the CLI, tests and independent benchmark.
"""
from __future__ import annotations

import argparse
from fractions import Fraction
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from importlib.resources import files
import json
import secrets
import threading
import webbrowser


def json_value(value):
    if isinstance(value, Fraction):
        return int(value) if value.denominator == 1 else str(value)
    raise TypeError(type(value).__name__)


def decimal_integer(value, name):
    if isinstance(value, bool):
        raise ValueError(f"{name} must be an integer")
    if isinstance(value, int):
        return value
    if isinstance(value, str) and value and value.lstrip("-").isdigit():
        if len(value) > 500:
            raise ValueError(f"{name} exceeds the 500-digit interface limit")
        return int(value)
    raise ValueError(f"{name} must be an integer")


def decimal_output(value):
    if isinstance(value, int) and value.bit_length() > 14000:
        raise ValueError("the exact answer has too many digits for this interface; supply a modulus")
    return str(value)


def compile_payload(spec):
    from .model import FiniteSystem, compile_system
    if not isinstance(spec, dict):
        raise ValueError("model must be a JSON object")
    system = FiniteSystem.from_dict(spec)
    if system.n > 10000 or system.alphabet > 16:
        raise ValueError("the local workbench supports at most 10,000 states and 16 actions")
    compilation = compile_system(system)
    return system, compilation


def evaluate(request):
    """Pure JSON request router, also convenient for notebooks and scripts."""
    operation = request.get("operation", "compile")
    # Math Lab questions carry their own exact inputs; they do not require a
    # finite action model. Keep this boundary ahead of finite-model compilation.
    if operation == "math-catalog":
        from ..mathlab import catalogue
        return catalogue()
    if operation == "math-lab":
        from ..mathlab import evaluate as evaluate_lab
        return evaluate_lab(request)
    from .histories import HistoryPopulation
    from .experiments import pair_experiment, adaptive_experiment
    from .series import compile_series, compile_observable_closure
    if operation == "pell-point":
        from .arithmetic import pell_point
        raw_model = request.get("model")
        if not isinstance(raw_model, dict):
            raise ValueError("model must be a JSON object")
        source = raw_model.get("pell")
        if not isinstance(source, dict):
            raise ValueError("this model has no Pell-orbit source")
        index = decimal_integer(request.get("index", "100"), "index")
        modulus = request.get("modulus")
        modulus = None if modulus in (None, "") else decimal_integer(modulus, "modulus")
        point = pell_point(source["D"], source["unit"], source["seed"], index, modulus)
        norm = source["seed"][0]**2-source["D"]*source["seed"][1]**2
        residual = point[0]**2-source["D"]*point[1]**2-norm
        return {"index": str(index), "modulus": modulus, "x": decimal_output(point[0]), "y": decimal_output(point[1]),
                "D": source["D"], "norm": norm,
                "norm_preserved": residual == 0 if modulus is None else residual % modulus == 0,
                "scope": "The orbit generated by the supplied seed and unit; no all-seed completeness claim."}
    system, compiled = compile_payload(request.get("model"))
    reduced = compiled.system
    if operation == "compile":
        return {"original_states": system.n, "reduced_states": reduced.n,
                "mapping": compiled.mapping, "blocks": compiled.blocks,
                "model": reduced.to_dict(), "metrics": compiled.metrics,
                "initial": compiled.mapping[system.initial]}
    if operation == "history":
        horizon = decimal_integer(request.get("horizon", 40), "horizon")
        budget = request.get("budget")
        budget = None if budget in (None, "") else decimal_integer(budget, "budget")
        trace = request.get("trace")
        pop = HistoryPopulation(reduced, horizon, budget, trace=trace,
                                start=compiled.mapping[system.initial])
        total = pop.count()
        selected = request.get("rank", "0")
        if request.get("word") is not None:
            word = request["word"]
            if isinstance(word, str):
                word = json.loads(word) if word.lstrip().startswith("[") else word.split()
            if not isinstance(word, (list, tuple)):
                raise ValueError("word must be an array of action names or indices")
            word = tuple(reduced.actions.index(a) if isinstance(a, str) else a for a in word)
            selected = pop.rank(word)
        elif request.get("sample") and total:
            import random
            selected = random.SystemRandom().randrange(total)
        rank = decimal_integer(selected, "rank")
        word = pop.unrank(rank) if total else ()
        state = compiled.mapping[system.initial]
        route = [state]
        for action in word:
            state = reduced.step(state, action)
            route.append(state)
        return {"count": str(total), "rank": str(rank),
                "word": [reduced.actions[a] for a in word], "indices": list(word),
                "route": route, "observations": [reduced.observations[s] for s in route],
                "cost": sum(reduced.costs[a] for a in word),
                "horizon": horizon, "budget": budget, "metrics": pop.metrics,
                "uniform": bool(request.get("sample"))}
    if operation == "series":
        series = compile_series(reduced, start=compiled.mapping[system.initial])
        index = decimal_integer(request.get("index", "100000000000000000000"), "index")
        modulus = request.get("modulus")
        modulus = None if modulus in (None, "") else decimal_integer(modulus, "modulus")
        if modulus is None and index > 10000:
            raise ValueError("supply a modulus for indices above 10,000; exact output may be enormous")
        out = series.record()
        out.update(index=str(index), modulus=modulus,
                   coefficient=decimal_output(series.coefficient(index, modulus=modulus)))
        return out
    if operation == "closure":
        demand = request.get("demand", "acceptance")
        if demand not in ("acceptance", "numeric-sensor"):
            raise ValueError("closure demand must be acceptance or numeric-sensor")
        if demand == "numeric-sensor":
            if any(type(x) is not int for x in reduced.observations):
                raise ValueError("numeric sensor closure requires integer-valued sensor labels")
            return compile_observable_closure(reduced, [reduced.observations]).record()
        return compile_observable_closure(reduced).record()
    if operation == "pair":
        x = decimal_integer(request.get("x", 0), "first state")
        y = decimal_integer(request.get("y", 1), "second state")
        return pair_experiment(system, x, y)
    if operation == "adaptive":
        belief = request.get("belief")
        if isinstance(belief, str):
            belief = [decimal_integer(x.strip(), "belief state") for x in belief.split(",") if x.strip()]
        prefix = request.get("prefix", [])
        if isinstance(prefix, str):
            prefix = json.loads(prefix) if prefix.strip() else []
        return adaptive_experiment(system, belief=belief, max_beliefs=4096, prefix=prefix)
    raise ValueError(f"unknown operation: {operation}")


def make_server(port=8765):
    """Bind to loopback and require a per-session token for every operation."""
    token = secrets.token_urlsafe(24)
    asset = files("perfectjet.observatory").joinpath("assets/index.html").read_text()

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *_):
            pass

        def send(self, status, data, content_type="application/json"):
            body = data.encode() if isinstance(data, str) else json.dumps(data, default=json_value).encode()
            self.send_response(status)
            self.send_header("Content-Type", content_type + "; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.end_headers()
            self.wfile.write(body)

        def authorized(self):
            return self.headers.get("X-Observatory-Token") == token

        def do_GET(self):
            if self.path == "/":
                return self.send(200, asset.replace("__SESSION_TOKEN__", token), "text/html")
            if self.path == "/api/examples" and self.authorized():
                from .examples import example_catalog
                return self.send(200, example_catalog())
            self.send(404, {"error": "unknown resource"})

        def do_POST(self):
            if self.path != "/api/evaluate" or not self.authorized():
                return self.send(403, {"error": "invalid session"})
            try:
                size = int(self.headers.get("Content-Length", "0"))
                if not 0 < size <= 4_000_000:
                    raise ValueError("request must contain at most 4 MB of JSON")
                request = json.loads(self.rfile.read(size))
                if not isinstance(request, dict):
                    raise ValueError("request must be an object")
                return self.send(200, evaluate(request))
            except (ValueError, TypeError, IndexError, KeyError, OverflowError, RuntimeError, ArithmeticError) as exc:
                return self.send(400, {"error": str(exc)})

    return ThreadingHTTPServer(("127.0.0.1", port), Handler)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Open the local PerfectJet Exact Observatory")
    parser.add_argument("--port", type=int, default=8765)
    parser.add_argument("--open", action="store_true", help="open the workbench in your browser")
    args = parser.parse_args(argv)
    if not 0 <= args.port <= 65535:
        parser.error("port must be between 0 and 65535")
    server = make_server(args.port)
    url = f"http://127.0.0.1:{server.server_port}"
    print(f"PerfectJet Exact Observatory: {url}\nPress Ctrl+C to stop.", flush=True)
    if args.open:
        threading.Timer(.25, lambda: webbrowser.open(url)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
