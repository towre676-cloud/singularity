#!/usr/bin/env python3
"""Transcribe the two decisive certificates into Lean literals (push P33).

Reads ``results/certificates/spectral.json`` and ``binary_census.json`` and
writes ``formal/Singularity/CertificateData.lean``.  This script is the only
trusted link between the JSON files and the kernel check: it copies numbers,
it computes nothing.  ``Singularity/Certificates.lean`` then proves in the
Lean kernel that the transcribed tables are the coefficients of the semantic
definition ``allCount`` from P07.

Usage, from the repository root:

    python3 formal/tools/gen_certificates.py           # rewrite the data module
    python3 formal/tools/gen_certificates.py --check   # fail if it is stale

The data module records the SHA-256 digest of each input file.
"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "formal" / "Singularity" / "CertificateData.lean"
SOURCES = [("spectral", "results/certificates/spectral.json"),
           ("binary", "results/certificates/binary_census.json")]


def edges(source):
    assert set(source) == {"n", "edges"}
    return "[" + ", ".join(f"({u}, {v})" for u, v in source["edges"]) + "]"


def table(rows):
    out = []
    for row in rows:
        assert all(len(t) == 2 for t in row)
        out.append("[" + ", ".join(f"({e}, {c})" for e, c in row) + "]")
    return "[\n    " + ",\n    ".join(out) + "]"


def poly(entries):
    # [degree, numerator, denominator]; the decisive differences are integral.
    assert all(d == 1 for _, _, d in entries), "non-integral coefficient"
    return "[" + ", ".join(f"({k}, {c})" for k, c, _ in entries) + "]"


def render():
    parts = [
        "/-",
        "  Singularity.CertificateData  (push P33): GENERATED by formal/tools/gen_certificates.py.",
        "  Do not edit by hand.  Literal transcription of the released certificates:",
    ]
    data = []
    for name, rel in SOURCES:
        raw = (ROOT / rel).read_bytes()
        parts.append(f"    {rel}  sha256 {hashlib.sha256(raw).hexdigest()}")
        data.append((name, rel, json.loads(raw)))
    parts += [
        "  This file is the trusted transcription boundary; every number in it is",
        "  checked against the semantic definition in Singularity/Certificates.lean.",
        "-/",
        "namespace Singularity.Cert",
        "",
    ]
    for name, rel, d in data:
        assert d["format"] == "singularity.certificate/1"
        c = d["comparison"]
        f = c["factorization"]
        assert d["graph"]["n"] == c["graph"]["n"]
        assert int(f["coefficient"]) == __import__("fractions").Fraction(f["coefficient"])
        assert all(k > 0 and m >= 0 for k, m in f["factors"])
        parts += [
            f"/-! ### {rel} (label `{d['label']}`) -/",
            f"def {name}N : Nat := {d['graph']['n']}",
            f"def {name}MaxVolume : Nat := {d['max_volume']}",
            f"/-- `graph.edges`. -/",
            f"def {name}G : List (Nat × Nat) := {edges(d['graph'])}",
            f"/-- `local_coefficients`: row `V` lists `(energy, count)`. -/",
            f"def {name}Table : List (List (Int × Nat)) := {table(d['local_coefficients'])}",
            f"/-- `normalized_coefficients`. -/",
            f"def {name}NormTable : List (List (Int × Nat)) := {table(d['normalized_coefficients'])}",
            f"/-- `comparison.graph.edges`. -/",
            f"def {name}CmpG : List (Nat × Nat) := {edges(c['graph'])}",
            f"/-- `comparison.local_coefficients`. -/",
            f"def {name}CmpTable : List (List (Int × Nat)) := {table(c['local_coefficients'])}",
            f"/-- `comparison.first_difference.volume`. -/",
            f"def {name}DiffVolume : Nat := {c['first_difference']['volume']}",
            f"/-- `comparison.first_difference.polynomial` as `(degree, coefficient)`. -/",
            f"def {name}DiffPoly : List (Int × Int) := {poly(c['first_difference']['polynomial'])}",
            f"/-- `comparison.factorization`: coefficient, monomial, `(degree, multiplicity)` factors. -/",
            f"def {name}FacCoeff : Int := {int(f['coefficient'])}",
            f"def {name}FacMonomial : Nat := {f['monomial']}",
            f"def {name}FacFactors : List (Nat × Nat) := [" + ", ".join(f"({k}, {m})" for k, m in f["factors"]) + "]",
            "",
        ]
    parts += ["end Singularity.Cert", ""]
    return "\n".join(parts)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} is stale; rerun formal/tools/gen_certificates.py")
        print("CertificateData.lean matches the certificates")
        return
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
