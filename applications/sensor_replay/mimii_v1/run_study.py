        masks = certificate['all_minimum_cost_masks']
        alternatives[objective] = [{'mask':mask, 'confirmation_balanced_accuracy':float(confirmation_table[mask-1][0]),
            'confirmation_balanced_accuracy_exact':qstring(confirmation_table[mask-1][0])} for mask in masks]
