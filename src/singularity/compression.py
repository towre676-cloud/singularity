"""Family compression of realizable graph states (OE10).

The full formal quotient of Chapter 15 compresses every state of the declared
coordinate space.  A graph family occupies a subset, so it may need fewer
coordinates.  Two notions must be kept apart.

* Initial-state compression: a linear map that is exact on the span F of the
  family's states, used to compare those states once.  Its least dimension
  is dim F / (F cap N), with N the invisible subspace.
* Attachment-closed compression: the family is closed under the context
  operators, so the compressed state must also evolve.  The relevant space is
  the reachable subspace Reach = span{M_w v}, and the least linear dimension
  is dim Reach / (Reach cap N): the reachable-observable part, as in Kalman's
  decomposition.

For the compiled graph operators both are computed exactly, and two theorems
(proved in Chapter 15, SNG-O13 and SNG-O14) explain the outcome.

* Cyclicity (SNG-O13).  Each operator acts on orbit block o as multiplication
  in Q[x]/x^(m_o), m_o = R+1-s-t, and every realizable graph state is a unit
  in every block.  Hence Reach = A v has dimension dim A for every realizable
  v, where A is the unital algebra generated by the operators.  If the
  orbit constants q^(d_C(s^2+t^2)) of one context are pairwise distinct and
  that context's kernel has a nonzero x^1 coefficient in every block, A is
  the full block algebra; every realizable state is then cyclic, and no
  attachment-closed family compresses below the full formal quotient.
* Star-family bound (SNG-O14).  For alpha leaves at one terminal, every state
  coordinate is a fixed linear combination of alpha^k q^(alpha r^2) with
  0 <= r <= R and k <= R - r.  So dim F <= (R+1)(R+2)/2, while the formal
  dimension grows cubically; the saving is proved for every R.
"""
from __future__ import annotations

from fractions import Fraction
from typing import Sequence

from .contexts import orbits
from .graph import Graph, _integer
from .graph_experiments import BoundaryExperimentSystem, _exact
from .observability import OperatorSystem, observable_closure
from .terminals import terminal_kernel


def independent_star(alpha: int, beta: int = 0, gamma: int = 0, delta: int = 0,
                     terminal_edge: bool = False) -> Graph:
    """Two terminals 0, 1 and an independent interior: alpha vertices adjacent
    only to terminal 0, beta only to 1, gamma to both, delta isolated."""
    counts = [_integer(c, name, minimum=0) for c, name in
              ((alpha, "alpha"), (beta, "beta"), (gamma, "gamma"), (delta, "delta"))]
    if not isinstance(terminal_edge, bool):
        raise TypeError("terminal_edge must be bool")
    n, edges = 2, []
    for neighbours, count in zip(((0,), (1,), (0, 1), ()), counts):
        for _ in range(count):
            edges.extend((t, n) for t in neighbours)
            n += 1
    if terminal_edge:
        edges.append((0, 1))
    return Graph(n, edges)


def star_transition(parameters: Sequence, context: str) -> tuple:
    """Typed transition of the star family under a standard context."""
    alpha, beta, gamma, delta, edge = parameters
    if context == "pendant_leaf_pair":
        return (alpha + 1, beta + 1, gamma, delta, edge)
    if context == "shared_neighbor":
        return (alpha, beta, gamma + 1, delta, edge)
    raise ValueError("unknown context for the star family")


def _rank(rows, columns: int) -> int:
    a = [list(r) for r in rows]
    rank = 0
    for c in range(columns):
        k = next((i for i in range(rank, len(a)) if a[i][c]), None)
        if k is None:
            continue
        a[rank], a[k] = a[k], a[rank]
        for i in range(len(a)):
            if i != rank and a[i][c]:
                f = a[i][c] / a[rank][c]
                a[i] = [u - f * w for u, w in zip(a[i], a[rank])]
        rank += 1
    return rank


def reachable_subspace(system: OperatorSystem, states) -> tuple:
    """A basis of span{M_w v : v in states, all words w}.

    This is the observation closure of the transposed system, whose
    observation rows are the states and whose generators are M_i^T."""
    if not isinstance(system, OperatorSystem):
        raise TypeError("system must be an OperatorSystem")
    n = system.dimension
    transposed = tuple(tuple(tuple(m[j][i] for j in range(n)) for i in range(n)) for m in system.operators)
    return observable_closure(OperatorSystem(n, transposed, tuple(states))).rows


def observable_dimension(observation_rows, vectors) -> int:
    """dim span(vectors) / (span(vectors) cap N) = rank of B restricted."""
    rows = tuple(observation_rows)
    if not rows:
        return 0
    return _rank([tuple(sum((b[k] * v[k] for k in range(len(v))), Fraction(0)) for b in rows)
                  for v in vectors], len(rows))


def compression_report(system: BoundaryExperimentSystem, graphs) -> dict:
    """Exact dimensions for a finite list of (graph, terminals) states."""
    operators = system.operator_system()
    rows = observable_closure(operators).rows
    states = [system.compile_graph(g, t) for g, t in graphs]
    family = _rank(states, system.dimension)
    reach = reachable_subspace(operators, states)
    return {"formal_dimension": system.dimension, "formal_quotient": len(rows),
            "family_span": family, "family_observable": observable_dimension(rows, states),
            "reachable": len(reach), "reachable_observable": observable_dimension(rows, reach)}


def cyclicity_certificate(system: BoundaryExperimentSystem, context: int = 0) -> dict:
    """Check the hypotheses of SNG-O13 for one context, exactly.

    Returns the orbit constants [x^0] kappa_o, whether they are pairwise
    distinct, and whether every block has nonzero [x^1] kappa_o (blocks of
    length one need no x^1 term).  Both true implies that the operator
    algebra is the full block algebra, so every realizable state is cyclic."""
    attachment = system.attachments[_integer(context, "context", minimum=0)]
    R = system.max_volume
    kernel = terminal_kernel(attachment.graph, attachment.terminals, R)
    constants, linear = {}, {}
    for o in orbits(R):
        cells = kernel.get(o, {})
        coefficient = lambda j: sum((Fraction(c) * system.q ** e for (jj, e), c in cells.items() if jj == j),
                                    Fraction(0))
        constants[o] = coefficient(0)
        linear[o] = coefficient(1) if R + 1 - sum(o) > 1 else None
    values = list(constants.values())
    distinct = len(set(values)) == len(values)
    nonzero = all(v is None or v != 0 for v in linear.values())
    return {"context": attachment.name, "orbits": len(values), "constants_distinct": distinct,
            "linear_terms_nonzero": nonzero, "full_block_algebra": distinct and nonzero}


def star_function_dimension(max_volume: int) -> int:
    """(R+1)(R+2)/2, the dimension bound of SNG-O14."""
    R = _integer(max_volume, "max_volume", minimum=0)
    return (R + 1) * (R + 2) // 2


def star_coordinates(max_volume: int, q, alpha: int) -> tuple:
    """The compressed coordinates (alpha^k q^(alpha r^2)) for r <= R, k <= R-r."""
    R = _integer(max_volume, "max_volume", minimum=0)
    q, alpha = _exact(q, "q"), _integer(alpha, "alpha", minimum=0)
    return tuple(Fraction(alpha) ** k * q ** (alpha * r * r) for r in range(R + 1) for k in range(R - r + 1))


def star_reconstruction(system: BoundaryExperimentSystem, verify_through: int | None = None):
    """The matrix C with compile(star(alpha)) = C * star_coordinates(alpha).

    C is fitted on alpha = 0..d-1 (d = (R+1)(R+2)/2), which requires the
    coordinate matrix to be invertible, and is then checked exactly on every
    alpha <= verify_through (default d + 4).  SNG-O14 proves that some C
    exists for all alpha; invertibility makes it unique."""
    R, q, n = system.max_volume, system.q, system.dimension
    d = star_function_dimension(R)
    V = [list(star_coordinates(R, q, a)) for a in range(d)]
    Y = [list(system.compile_graph(independent_star(a), (0, 1))) for a in range(d)]
    # Solve V^T C^T = Y^T row by row: C = Y^T (V^T)^(-1).
    aug = [V[a] + Y[a] for a in range(d)]  # rows: coordinates | state, for each alpha
    # Gaussian elimination on the d x d system V X = Y, X = C^T.
    for c in range(d):
        k = next((i for i in range(c, d) if aug[i][c]), None)
        if k is None:
            raise ArithmeticError("star coordinate matrix is singular at this q and R")
        aug[c], aug[k] = aug[k], aug[c]
        pivot = aug[c][c]
        aug[c] = [x / pivot for x in aug[c]]
        for i in range(d):
            if i != c and aug[i][c]:
                f = aug[i][c]
                aug[i] = [u - f * w for u, w in zip(aug[i], aug[c])]
    X = [row[d:] for row in aug]                       # d x n, X = C^T
    C = tuple(tuple(X[k][i] for k in range(d)) for i in range(n))
    last = d + 4 if verify_through is None else _integer(verify_through, "verify_through", minimum=0)
    for a in range(last + 1):
        coords = star_coordinates(R, q, a)
        predicted = tuple(sum((C[i][k] * coords[k] for k in range(d)), Fraction(0)) for i in range(n))
        if predicted != system.compile_graph(independent_star(a), (0, 1)):
            raise ArithmeticError(f"star reconstruction fails at alpha={a}")
    return C
