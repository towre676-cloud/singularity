"""Effective prefix certificates whose generation mechanisms are explicit.

No sampled recurrence, parameter count, or temporary ideal stabilization is
accepted. The new graph family is one weighted edge and k known isolates.
Its all-coefficient ideal is generated by its first coefficient difference.
"""
from dataclasses import dataclass
from fractions import Fraction
from math import comb
from .graph import Graph
from .periodic import PeriodicModel,periodic_cutoff,direct_coefficients


def _q(x):
    if isinstance(x,bool) or not isinstance(x,(int,Fraction)):raise TypeError('exact rational required')
    return Fraction(x)


def _nat(x,minimum=0):
    if isinstance(x,bool) or not isinstance(x,int) or x<minimum:raise ValueError('integer outside range')
    return x


@dataclass(frozen=True)
class FiniteStatePrefixCertificate:
    transition: tuple
    initial: tuple
    output: tuple
    family: str='declared-linear-state'

    def __post_init__(self):
        A=tuple(tuple(map(_q,row)) for row in self.transition);s=tuple(map(_q,self.initial));c=tuple(map(_q,self.output))
        n=len(s)
        if self.family!='declared-linear-state' or not 1<=n<=64 or len(A)!=n or len(c)!=n or any(len(row)!=n for row in A):
            raise ValueError('invalid proved finite-state family')
        object.__setattr__(self,'transition',A);object.__setattr__(self,'initial',s);object.__setattr__(self,'output',c)

    def coefficients(self,R):
        s=self.initial;out=[]
        for _ in range(_nat(R)+1):
            out.append(sum((a*b for a,b in zip(self.output,s)),Fraction()))
            s=tuple(sum((a*b for a,b in zip(row,s)),Fraction()) for row in self.transition)
        return tuple(out)


@dataclass(frozen=True)
class RecurrencePrefixCertificate:
    """The proved binomial ODE family; arbitrary guessed recurrences rejected."""
    parameter: Fraction
    family: str='binomial-ode'

    def __post_init__(self):
        if self.family!='binomial-ode':raise ValueError('unproved recurrence family')
        object.__setattr__(self,'parameter',_q(self.parameter))

    def coefficients(self,R):
        out=[Fraction(1)]
        for n in range(_nat(R)):out.append(out[-1]*(n+self.parameter)/(n+1))
        return tuple(out)


@dataclass(frozen=True)
class IdealClosurePrefixCertificate:
    """L for one q-weighted edge and k known isolated labeled vertices."""
    parameter: Fraction
    isolates: int=0
    family: str='one-edge-isolates'

    def __post_init__(self):
        if self.family!='one-edge-isolates':raise ValueError('unproved ideal-generation family')
        q=_q(self.parameter)
        if not 0<=q<=1:raise ValueError('declared parameter domain is 0<=q<=1')
        object.__setattr__(self,'parameter',q);_nat(self.isolates)

    @property
    def exceptional_stratum(self):
        return 'zero-edge-weight' if self.parameter==0 else 'unit-weight-rational' if self.parameter==1 else 'nonperiodic-nonrational'

    def coefficients(self,R):
        q=self.parameter;k=self.isolates;out=[]
        edge=[sum((Fraction(1) if d==0 else 2*q**(d*d) for d in range(r%2,r+1,2)),Fraction()) for r in range(_nat(R)+1)]
        for r in range(R+1):
            out.append(edge[r] if not k else sum((edge[s]*comb(r-s+k-1,k-1) for s in range(r+1)),Fraction()))
        return tuple(out)


@dataclass(frozen=True)
class PeriodicPrefixCertificate:
    model: PeriodicModel
    def __post_init__(self):
        if not isinstance(self.model,PeriodicModel):raise TypeError('PeriodicModel required')
    def coefficients(self,R,max_profiles=1_000_000):return tuple(direct_coefficients(self.model,R,max_profiles))


def ideal_difference_quotient(index,q,eta,isolates=0):
    """Explicit H_r with f_r(q)-f_r(eta)=2(q-eta)H_r; no division q-eta.

    Telescoping q^m-eta^m=(q-eta) sum_{i=0}^{m-1}q^(m-1-i)eta^i
    proves every future coefficient belongs to the first-difference ideal.
    """
    r=_nat(index);q=_q(q);eta=_q(eta);k=_nat(isolates);answer=Fraction()
    for s in range(r+1):
        multiplicity=(int(s==r) if k==0 else comb(r-s+k-1,k-1))
        if not multiplicity:continue
        for d in range(s%2,s+1,2):
            if d:
                answer+=multiplicity*sum((q**(d*d-1-i)*eta**i for i in range(d*d)),Fraction())
    return answer


def comparison_recurrence(a,b,index):
    """Common difference recurrence, not subtraction of different recurrences.

    (n+1)(n+2)y[n+2] -(n+1)(2n+a+b+1)y[n+1]
       +(n+a)(n+b)y[n]=0. Leading coefficient never vanishes at n>=0.
    """
    a=_q(a);b=_q(b);n=_nat(index)
    return ((n+a)*(n+b),-(n+1)*(2*n+a+b+1),Fraction((n+1)*(n+2)))


def compare_prefix(first,second,max_profiles=1_000_000):
    verify_certificate(first);verify_certificate(second)
    if type(first) is not type(second):raise ValueError('different original family contracts')
    if isinstance(first,FiniteStatePrefixCertificate):
        cutoff=len(first.initial)+len(second.initial)-1;mechanism='combined-state Cayley-Hamilton'
    elif isinstance(first,RecurrencePrefixCertificate):cutoff=1;mechanism='proved common polynomial-index difference recurrence'
    elif isinstance(first,IdealClosurePrefixCertificate):
        if first.isolates!=second.isolates:raise ValueError('comparison requires same known isolate count')
        cutoff=1;mechanism='explicit all-coefficient ideal generation by f1 difference'
    else:
        a,b=first.model,second.model
        if a.n!=b.n or a.modulus!=b.modulus:raise ValueError('periodic comparison requires same n and M')
        cutoff=periodic_cutoff(a.n,a.modulus);mechanism='periodic palindromic numerator'
    if isinstance(first,PeriodicPrefixCertificate):
        xs=first.coefficients(cutoff,max_profiles);ys=second.coefficients(cutoff,max_profiles)
    else:xs=first.coefficients(cutoff);ys=second.coefficients(cutoff)
    for i,(x,y) in enumerate(zip(xs,ys)):
        if x!=y:return {'equal':False,'cutoff':cutoff,'first_difference':i,'coefficients':(x,y),'mechanism':mechanism}
    return {'equal':True,'cutoff':cutoff,'first_difference':None,'mechanism':mechanism}


def verify_certificate(cert):
    if type(cert) not in (FiniteStatePrefixCertificate,RecurrencePrefixCertificate,IdealClosurePrefixCertificate,PeriodicPrefixCertificate):
        raise ValueError('finite samples or unproved recurrence are not a certificate')
    # Frozen certificate constructors validate the complete declared mechanism.
    return True


def _encode_q(x):return [x.numerator,x.denominator]

def _decode_q(x):
    if not isinstance(x,list) or len(x)!=2 or any(isinstance(a,bool) or not isinstance(a,int) for a in x) or x[1]<=0:
        raise ValueError('canonical rational pair required')
    q=Fraction(*x)
    if _encode_q(q)!=x:raise ValueError('rational pair must be reduced')
    return q


def certificate_to_dict(cert):
    verify_certificate(cert)
    base={'schema':'singularity.prefix-certificate/1'}
    if isinstance(cert,FiniteStatePrefixCertificate):
        base.update(kind='finite-state',transition=[[_encode_q(x) for x in row] for row in cert.transition],
                    initial=[_encode_q(x) for x in cert.initial],output=[_encode_q(x) for x in cert.output])
    elif isinstance(cert,RecurrencePrefixCertificate):base.update(kind='binomial-recurrence',parameter=_encode_q(cert.parameter))
    elif isinstance(cert,IdealClosurePrefixCertificate):base.update(kind='edge-ideal',parameter=_encode_q(cert.parameter),isolates=cert.isolates)
    else:base.update(kind='periodic',n=cert.model.n,edges=[list(e) for e in cert.model.graph.edges],modulus=cert.model.modulus,
                     phases=[[list(e),a] for e,a in cert.model.phases])
    return base


def parse_certificate(data):
    if not isinstance(data,dict) or data.get('schema')!='singularity.prefix-certificate/1':raise ValueError('prefix schema mismatch')
    kind=data.get('kind');common={'schema','kind'}
    if kind=='finite-state' and set(data)==common|{'transition','initial','output'}:
        return FiniteStatePrefixCertificate(tuple(tuple(_decode_q(x) for x in row) for row in data['transition']),
            tuple(_decode_q(x) for x in data['initial']),tuple(_decode_q(x) for x in data['output']))
    if kind=='binomial-recurrence' and set(data)==common|{'parameter'}:return RecurrencePrefixCertificate(_decode_q(data['parameter']))
    if kind=='edge-ideal' and set(data)==common|{'parameter','isolates'}:return IdealClosurePrefixCertificate(_decode_q(data['parameter']),data['isolates'])
    if kind=='periodic' and set(data)==common|{'n','edges','modulus','phases'}:
        if len({tuple(e) for e,a in data['phases']})!=len(data['phases']):raise ValueError('duplicate phase edge')
        return PeriodicPrefixCertificate(PeriodicModel(Graph(data['n'],data['edges']),data['modulus'],{tuple(e):a for e,a in data['phases']}))
    raise ValueError('unknown kind, missing fields, or unproved recurrence payload')
